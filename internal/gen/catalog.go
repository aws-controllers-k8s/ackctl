// arnPrimaryTemplate is the sentinel arn_template for a resource whose identifier
// simply IS its ARN, so there is nothing to decompose.
const arnPrimaryTemplate = "<arn>"

// catalogComment is written into the generated file. It names the tool and the
// inputs so a reader knows the file is derived, and where from.
const catalogComment = "Generated by cmd/ack-catalog-gen from ACK controller releases + " +
	"the AWS Service Reference API, plus metadata/overrides.json. DO NOT EDIT BY HAND."

// Unsupported reasons. These are user-facing: they appear verbatim in
// `ack list adoptable --unsupported` and in the error when someone asks to
// adopt such a kind, so each says what is missing and whether it is fixable.
const (
	reasonNoIdentifiers     = "the controller declares no adoption identifiers"
	reasonNoGrammarService  = "no published ARN grammar for the service"
	reasonNoGrammarResource = "no matching resource type in the ARN grammar (needs override)"
	reasonNoTypeFilter      = "no Tagging API type filter (needs override)"
	reasonKeyNotInARN       = "required key not in ARN (needs override/describe)"
)

type Catalog struct {
	Comment     string                 `json:"_comment"`
	Resources   []metadata.Resource    `json:"resources"`
	Unsupported []metadata.Unsupported `json:"unsupported"`
}

// BuildInput is everything Build needs. Each field comes from its own stage, so
// the stages can be tested and re-run independently.
type BuildInput struct {
	Upstream []Upstream
	// Grammar is the per-service ARN grammar (resource types and their ARN templates)
	// from the AWS Service Reference API.
	Grammar   SvcRef
	Overrides *Overrides
}

// Build assembles the catalog, landing every resource in exactly one of Resources or
// Unsupported so an unmappable resource is a visible gap rather than an absence.
//
// Precedence: an `unsupported` override, then ARN-primary resources, then a `resources`
// override supplying the templates, then automatic lookup. Every ARN shape that binds
// the required keys is kept.
func Build(in BuildInput) (*Catalog, error) {
	cat := &Catalog{Comment: catalogComment}
	supported := map[string]bool{}

	for _, u := range in.Upstream {
		key := u.Key()
		unsupported := func(reason string) {
			cat.Unsupported = append(cat.Unsupported, metadata.Unsupported{
				Resource: key, Kind: u.Kind, Reason: reason,
			})
		}

		ov := in.Overrides.Resources[key]
		if ov != nil && ov.ARNPrimary != u.ARNPrimary {
			return nil, fmt.Errorf("override %q says arn_primary=%v but the controller "+
				"declares %v: the override would silently not apply", key, ov.ARNPrimary, u.ARNPrimary)
		}

		if uov, ok := in.Overrides.Unsupported[key]; ok {
			unsupported(uov.Reason)
			continue
		}
		// A controller can declare PopulateResourceFromAnnotation and require
		// nothing. There is then no identifier to put in adoption-fields, so the
		// resource cannot be adopted by annotation at all — reported, not dropped.
		if len(u.Required) == 0 {
			unsupported(reasonNoIdentifiers)
			continue
		}

		entry := metadata.Resource{
			Service:     u.Service,
			ResourceDir: u.ResourceDir,
			Kind:        u.Kind,
			Group:       u.Group,
			Version:     u.Version,
			ARNPrimary:  u.ARNPrimary,
		}

		if u.ARNPrimary {
			// Even with nothing to decompose, a type filter is required: without
			// one the CLI cannot scope its GetResources query, so shipping the
			// entry as supported would just fail at runtime.
			tf := ""
			if ov != nil {
				tf = ov.ResourceTypeFilter
			} else if tf2, ok := autoTypeFilter(u, in.Grammar); ok {
				tf = tf2
			}
			if tf == "" {
				unsupported(reasonNoTypeFilter)
				continue
			}
			entry.ResourceTypeFilter = tf
			entry.Templates = []metadata.Template{{
				ARNTemplate: arnPrimaryTemplate,
				Bindings:    []metadata.Binding{{Key: "arn", From: "${ARN}"}},
			}}
			cat.Resources = append(cat.Resources, entry)
			supported[key] = true
			continue
		}

		var forms []ARNForm
		var typeFilter string
		switch {
		case ov != nil:
			for _, tmpl := range ov.ARNTemplates {
				forms = append(forms, newARNForm(tmpl))
			}
			typeFilter = ov.ResourceTypeFilter
		default:
			svc, ok := in.Grammar[Namespace(u.Service)]
			if !ok {
				unsupported(reasonNoGrammarService)
				continue
			}
			res, ok := svc.PickResource(u.ResourceDir)
			if !ok {
				unsupported(reasonNoGrammarResource)
				continue
			}
			forms = res.Forms
			typeFilter = strings.ToLower(svc.Namespace + ":" + res.Type)
		}

		target := naming.Target{Kind: u.Kind, ResourceDir: u.ResourceDir, Service: u.Service}
		for _, form := range forms {
			// Hand-asserted bindings are removed from the pool before matching:
			// they escape the name rule by design, and leaving them in would let
			// them also be matched automatically and produce two answers.
			split, err := splitManualBindings(u, form, in.Overrides)
			if err != nil {
				return nil, err
			}
			bindings, err := naming.Bind(split.autoRequired, form.PathPlaceholders,
				form.HasAccount, target)
			if err != nil {
				continue // this shape does not carry the identifiers; try the next
			}
			for k, from := range split.manualRequired {
				bindings[k] = from
			}
			claimed := claimedPlaceholders(bindings, form.PathPlaceholders)
			for p := range claimedPlaceholders(split.manualOptional, form.PathPlaceholders) {
				claimed[p] = true
			}
			optional := naming.BindOptional(split.autoOptional, form.PathPlaceholders,
				form.HasAccount, claimed, target)
			for k, from := range split.manualOptional {
				optional[k] = from
			}
			entry.Templates = append(entry.Templates, metadata.Template{
				ARNTemplate: form.Template,
				Bindings:    orderedBindings(u.Required, u.Optional, bindings, optional),
			})
		}
		if len(entry.Templates) == 0 {
			unsupported(reasonKeyNotInARN)
			continue
		}
		if typeFilter == "" {
			unsupported(reasonNoTypeFilter)
			continue
		}
		entry.ResourceTypeFilter = typeFilter
		cat.Resources = append(cat.Resources, entry)
		supported[key] = true
	}

	// A binding override that leaves its resource unsupported is a defect (typo'd key,
	// stale placeholder), not settled history.
	for key := range in.Overrides.Bindings {
		resourceKey, field, _ := strings.Cut(key, ".")
		if _, isUnsupported := in.Overrides.Unsupported[resourceKey]; isUnsupported {
			return nil, fmt.Errorf("binding override %q contradicts the unsupported "+
				"override for %s: remove one of them", key, resourceKey)
		}
		u, ok := upstreamFind(in.Upstream, resourceKey)
		if !ok {
			continue // not a controller in this scan; nothing to contradict
		}
		// An override on an unread key applies to nothing, and the adoptability check
		// below cannot see it because an unread key does not gate support.
		if !declaresKey(u, field) {
			return nil, fmt.Errorf("binding override %q names a key %s does not read "+
				"(it declares required [%s] optional [%s]): fix the key or drop the override",
				key, resourceKey, strings.Join(u.Required, " "), strings.Join(u.Optional, " "))
		}
		if !supported[resourceKey] {
			return nil, fmt.Errorf("binding override %q did not make %s adoptable: "+
				"check the key and the placeholders it references", key, resourceKey)
		}
	}

	sort.Slice(cat.Resources, func(i, j int) bool {
		if cat.Resources[i].Service != cat.Resources[j].Service {
			return cat.Resources[i].Service < cat.Resources[j].Service
		}
		return cat.Resources[i].ResourceDir < cat.Resources[j].ResourceDir
	})
	sort.Slice(cat.Unsupported, func(i, j int) bool {
		return cat.Unsupported[i].Resource < cat.Unsupported[j].Resource
	})
	return cat, nil
}

func upstreamFind(upstream []Upstream, key string) (Upstream, bool) {
	for _, u := range upstream {
		if u.Key() == key {
			return u, true
		}
	}
	return Upstream{}, false
}

// declaresKey reports whether the controller reads this adoption-fields key at all.
func declaresKey(u Upstream, key string) bool {
	for _, k := range append(append([]string(nil), u.Required...), u.Optional...) {
		if k == key {
			return true
		}
	}
	return false
}

// claimedPlaceholders marks every path placeholder a binding already reads.
func claimedPlaceholders(bindings map[string]string, pathPlaceholders []string) map[string]bool {
	claimed := map[string]bool{}
	for _, from := range bindings {
		for _, m := range placeholderRE.FindAllStringSubmatch(from, -1) {
			for _, p := range pathPlaceholders {
				if strings.EqualFold(p, m[1]) {
					claimed[p] = true
				}
			}
		}
	}
	return claimed
}

// manualSplit records which keys an override binds by hand and which are left to
// automatic matching, kept apart by required/optional because only the required ones
// gate whether an ARN form is usable at all.
type manualSplit struct {
	autoRequired   []string
	autoOptional   []string
	manualRequired map[string]string
	manualOptional map[string]string
}

// splitManualBindings separates the keys a binding override claims from those left for
// automatic matching, and checks that every placeholder a manual "from" references still
// exists. Without that check an upstream template revision would only surface at runtime
// as skipped resources. Optional keys are split the same way as required ones, or an
// override on one would silently never apply.
func splitManualBindings(u Upstream, form ARNForm, ov *Overrides) (*manualSplit, error) {
	available := map[string]bool{"partition": true, "region": true, "account": true, "arn": true}
	for _, p := range form.PathPlaceholders {
		available[strings.ToLower(p)] = true
	}

	split := &manualSplit{
		manualRequired: map[string]string{},
		manualOptional: map[string]string{},
	}
	for _, spec := range []struct {
		keys   []string
		auto   *[]string
		manual map[string]string
	}{
		{u.Required, &split.autoRequired, split.manualRequired},
		{u.Optional, &split.autoOptional, split.manualOptional},
	} {
		for _, k := range spec.keys {
			b, ok := ov.Bindings[u.Key()+"."+k]
			if !ok {
				*spec.auto = append(*spec.auto, k)
				continue
			}
			for _, m := range placeholderRE.FindAllStringSubmatch(b.From, -1) {
				if !available[strings.ToLower(m[1])] {
					return nil, fmt.Errorf(
						"binding override %q references ${%s}, which is not in the ARN template %q "+
							"(the grammar may have changed upstream; re-check the override)",
						u.Key()+"."+k, m[1], form.Template)
				}
			}
			spec.manual[k] = b.From
		}
	}
	return split, nil
}

func autoTypeFilter(u Upstream, grammar SvcRef) (string, bool) {
	svc, ok := grammar[Namespace(u.Service)]
	if !ok {
		return "", false
	}
	res, ok := svc.PickResource(u.ResourceDir)
	if !ok {
		return "", false
	}
	return strings.ToLower(svc.Namespace + ":" + res.Type), true
}

// orderedBindings emits bindings in ACK's own declaration order, required keys first. The
// order is significant because CR names walk bindings in sequence, so re-ordering would
// rename every already-adopted resource.
func orderedBindings(required, optional []string, bound, boundOptional map[string]string) []metadata.Binding {
	out := make([]metadata.Binding, 0, len(required)+len(boundOptional))
	for _, k := range required {
		out = append(out, metadata.Binding{Key: k, From: bound[k]})
	}
	for _, k := range optional {
		if from, ok := boundOptional[k]; ok {
			out = append(out, metadata.Binding{Key: k, From: from})
		}
	}
	return out
}

// Marshal renders the catalog exactly as the committed file is formatted, so a
// regeneration that changes nothing produces a byte-identical file and an empty
// diff.
func (c *Catalog) Marshal() ([]byte, error) {
	b, err := json.MarshalIndent(c, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(b, '\n'), nil
}

func (c *Catalog) Summary() string {
	return fmt.Sprintf("%d supported, %d unsupported (%d total)",
		len(c.Resources), len(c.Unsupported), len(c.Resources)+len(c.Unsupported))
}
